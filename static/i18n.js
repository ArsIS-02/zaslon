// шаблоны для строк с переменными (сообщения панели, агента и старые записи журнала)
const PATTERNS = [
  [/^Хост (.+) не ответил за (\d+) с$/, (m) => `Host ${m[1]} did not respond within ${m[2]} s`],
  [/^Хост с адресом (.+) уже добавлен$/, (m) => `Host with address ${m[1]} is already added`],
  [/^Нет связи с (.+) по SSH: (.+)$/, (m) => `No SSH connection to ${m[1]}: ${m[2]}`],
  [/^Команда (.+) не ответила за (\d+) с$/, (m) => `Command ${m[1]} did not respond within ${m[2]} s`],
  [/^Не найдена команда (.+) на хосте$/, (m) => `Command ${m[1]} not found on the host`],
  [/^Булева опция (.+) не найдена$/, (m) => `SELinux boolean ${m[1]} not found`],
  [/^Изменение (.+) не найдено$/, (m) => `Change ${m[1]} not found`],
  [/^Агент на (.+) вернул непонятный ответ(.*)$/, (m) => `Agent on ${m[1]} returned an unclear response${m[2]}`],
  [/^Добавлен хост (.+?) \((.+?)\)(.*)$/, (m) => `Host ${m[1]} added (${m[2]})${m[3] ? " — without a connection check" : ""}`],
  [/^Удалён хост (.+)$/, (m) => `Host ${m[1]} removed`],
  [/^(Открыть|Закрыть) порт (\S+) в зоне (\S+)$/, (m) => `${m[1] === "Открыть" ? "Open" : "Close"} port ${m[2]} in zone ${m[3]}`],
  [/^Некорректный запрос: (.+)$/, (m) => `Invalid request: ${m[1]}`],
  [/^Откатано: (.+)$/, (m) => `Rolled back: ${m[1]}`],
  [/^Подтверждено: (.+)$/, (m) => `Confirmed: ${m[1]}`],
  [/^Меняю (.+)$/, (m) => `Changing ${m[1]}`],
];

export function getLang() {
  try { return localStorage.getItem(LANG_KEY) === "en" ? "en" : "ru"; } catch (e) { return "ru"; }
}

export function setLang(l) {
  try { localStorage.setItem(LANG_KEY, l === "en" ? "en" : "ru"); } catch (e) { /* без хранилища */ }
  document.documentElement.lang = l === "en" ? "en" : "ru";
  applyStatic();
}

// перевод строки; для русского возвращает исходный текст
export function T(s) {
  if (s === null || s === undefined) return "";
  const str = String(s);
  if (getLang() !== "en") return str;
  if (Object.prototype.hasOwnProperty.call(EN, str)) return EN[str];
  for (const [re, f] of PATTERNS) {
    const m = str.match(re);
    if (m) return f(m);
  }
  return str;
}

// склейка кусков строки: русские фрагменты переводятся, числа и данные — нет
export function tc(...parts) {
  return parts.map((p) => (typeof p === "string" && /[А-Яа-яЁё]/.test(p) ? T(p) : (p === null || p === undefined ? "" : String(p)))).join("");
}

// статические подписи в разметке: <span data-i18n="Журнал">
export function applyStatic() {
  document.querySelectorAll("[data-i18n]").forEach((n) => { n.textContent = T(n.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-title]").forEach((n) => { n.setAttribute("title", T(n.getAttribute("data-i18n-title"))); });
}

// ---------- тема: тёмная по умолчанию ----------
export function getTheme() {
  try { return localStorage.getItem(THEME_KEY) === "light" ? "light" : "dark"; } catch (e) { return "dark"; }
}

export function setTheme(t) {
  const v = t === "light" ? "light" : "dark";
  try { localStorage.setItem(THEME_KEY, v); } catch (e) { /* без хранилища */ }
  document.documentElement.dataset.theme = v;
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute("content", v === "light" ? "#f4f6f9" : "#182027");
}
